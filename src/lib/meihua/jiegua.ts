/** 生成梅花易数详细解读 */
export function interpretMeihua(result: MeiHuaResult, question: string): string {
  const benMeaning = GUA_MEANINGS[result.benGua.name] || "请结合具体卦象分析。";
  const bianMeaning = result.bianGua.name !== result.benGua.name
    ? GUA_MEANINGS[result.bianGua.name] || ""
    : "";
  const huMeaning = result.huGua
    ? GUA_MEANINGS[result.huGua.name] || ""
    : "";

  const tiYong = result.tiYong;
  const advice = getAdvice(tiYong.relation);

  let text = "";

  // 1. 总体判断
  text += `**卦象总览：**本卦「${result.benGua.name}」${benMeaning}\n\n`;

  // 2. 体用关系分析
  text += `**体用分析：**体卦为「${tiYong.ti.gua}」（${tiYong.ti.wx}），代表你自身；用卦为「${tiYong.yong.gua}」（${tiYong.yong.wx}），代表「${question}」这件事。\n\n`;
  text += `${tiYong.relation}——${tiYong.verdict}\n\n`;

  // 3. 互卦（过程）
  if (result.huGua && huMeaning) {
    text += `**过程提示（互卦）：**互卦「${result.huGua.name}」${huMeaning}\n\n`;
  }

  // 4. 变卦（结果）
  if (bianMeaning) {
    text += `**结果指示（变卦）：**变卦「${result.bianGua.name}」${bianMeaning}\n\n`;
  }

  // 5. 行动建议
  text += `**给你的建议：**${advice}`;

  return text;
}

