export function cityToLon(city: string): number {
  // Exact match
  if (CITY_LON[city]) return CITY_LON[city];
  // Partial match (e.g. "北京朝阳" → "北京")
  for (const [name, lon] of Object.entries(CITY_LON)) {
    if (city.includes(name)) return lon;
  }
  // Default: Beijing
  return 120;
}
